package utils

func Fsuma(num1 float64, num2 float64) float64 {
	return num1 + num2
}

func Fresta(num1 float64, num2 float64) float64 {
	return num1 - num2
}

func Fmultiplicacion(num1 float64, num2 float64) float64 {
	return num1 * num2
}

func Fdivision(num1 float64, num2 float64) float64 {
	return num1 / num2
}
